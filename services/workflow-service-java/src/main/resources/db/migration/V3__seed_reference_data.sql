         WHEN 'SUPERSTRUCTURE'           THEN ARRAY['METHOD_STATEMENT','MIX_DESIGN','STRUCTURAL_DRAWING']
         WHEN 'ROOF'                     THEN ARRAY['ROOF_SPEC','WATERPROOFING_SPEC','INSULATION_CERT']
         WHEN 'BUILDING_ENVELOPE'        THEN ARRAY['FACADE_DRAWINGS','WINDOW_SPEC','WATERPROOFING_SPEC']
         WHEN 'INTERIOR_PARTITIONS'      THEN ARRAY['PARTITION_DRAWINGS','FIRE_RATING_SPEC']
         WHEN 'MEP_ROUGHIN'              THEN ARRAY['MEP_DRAWING','INSPECTION_REPORT','TEST_PROCEDURE']
         WHEN 'INTERIOR_FINISH'          THEN ARRAY['FINISH_SCHEDULE','SAMPLE_APPROVAL']
         WHEN 'EXTERIOR_WORKS'           THEN ARRAY['LANDSCAPING_PLAN','PAVING_PLAN','EXTERNAL_LIGHTING_PLAN']
         WHEN 'TESTING_COMMISSIONING'    THEN ARRAY['TEST_PROCEDURES','COMMISSIONING_PLAN','PERFORMANCE_CERTS']
         WHEN 'QUALITY_ASSURANCE'        THEN ARRAY['QA_PLAN','INSPECTION_REPORT','NCR_FORM']
         WHEN 'SAFETY_MANAGEMENT'        THEN ARRAY['SAFETY_PLAN','INCIDENT_REPORT']
         WHEN 'PROCUREMENT'              THEN ARRAY['MATERIAL_REQUEST','VENDOR_QUOTATION','PURCHASE_ORDER']
         WHEN 'EQUIPMENT_MANAGEMENT'     THEN ARRAY['EQUIPMENT_LIST','MANUFACTURER_SPECS','MAINTENANCE_MANUAL']
